def _ratio_suffix(ratio):
    return "" if ratio == 1.0 else f"_r{ratio:g}"


def synthetic_path(model, ratio=1.0):
    """Synthetic anomalies generated by ``model`` ('vae' or 'vaegan')."""
    return SYNTHETIC_DIR / f"synthetic_{model}{_ratio_suffix(ratio)}.csv"


def combined_path(model, ratio=1.0):
    """Cleaned real data + synthetic anomalies generated by ``model``."""
    return SYNTHETIC_DIR / f"combined_data_{model}{_ratio_suffix(ratio)}.csv"


